/**
 * 层级令牌。
 *
 * 分散在各处的 z-index 迟早会打架（"我再加个 1"），所以集中在这里。
 * 取值之间留出空档，方便插入新的中间层而不用重排。
 *
 * **下拉必须排在对话框之上。** 对话框里也会放下拉（专业参数面板里有十一个），
 * 而 Base UI 的下拉是 portal 到 body 上的，与对话框本体不是同一棵子树——
 * 排在下面就会被对话框的遮罩盖住，点选项点不动的那种坏法。
 * 上游靠调用方自己传 `DROPDOWN_IN_MODAL` 解决，本项目直接把这层定死在上面：
 * 对话框开着的时候，主窗口里的下拉本来就打不开，不需要两档。
 */
export const Z_INDEX = {
  /** 常规内容 */
  BASE: 0,
  /** 对话框遮罩 */
  MODAL_BACKDROP: 50,
  /** 对话框本体（必须在遮罩之上） */
  MODAL_CONTENT: 51,
  /** 下拉、菜单、气泡（必须在对话框本体之上，见上方说明） */
  DROPDOWN: 60,
  /** 全局投放提示这类压住整屏的浮层 */
  OVERLAY: 90,
  /** 提示气泡 */
  TOOLTIP: 100,
} as const;
